import { afterEach, expect, it } from 'vitest'
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { auditScienceRelease, sanitizeScienceRelease } from '../scripts/science-release-privacy.mjs'

const roots: string[] = []
afterEach(() => { for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true }) })
function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'science-privacy-'))
  roots.push(root)
  const write = (name: string, contents: string | Buffer) => {
    const path = join(root, name)
    mkdirSync(join(path, '..'), { recursive: true })
    writeFileSync(path, contents)
  }
  write('resources/app/package.json', JSON.stringify({ dshScience: true }))
  return { root, write }
}

it('removes generated path comments without changing code or pinned resource bytes', () => {
  const { root, write } = fixture()
  const code = 'export const value = 4\n'
  write('resources/app/client.js', '//#region C:/build/science/style.css\n' + code + '//#endregion\n')
  write('resources/app/node_modules/.bin/tool', '#!/bin/sh\n# cmd-shim-target=C:/build/science/bin.js\nexec node "$@"\n')
  write('resources/app/assets/skill.md', 'Keep this upstream instruction byte for byte.\n')
  expect(auditScienceRelease(root, ['C:/build/science']).findings).toHaveLength(2)
  expect(sanitizeScienceRelease(root).rewrittenComments).toBe(2)
  expect(readFileSync(join(root, 'resources/app/client.js'), 'utf8')).toBe(code)
  expect(readFileSync(join(root, 'resources/app/assets/skill.md'), 'utf8')).toBe('Keep this upstream instruction byte for byte.\n')
  expect(auditScienceRelease(root, ['C:/build/science']).findings).toEqual([])
})

it('omits generated bytecode and local pip metadata and creates relocatable console commands', () => {
  const { root, write } = fixture()
  const python = 'resources/runtime/primary-runtime/dependencies/python/'
  write(python + 'Lib/site-packages/fonttools-1.0.dist-info/entry_points.txt', '[console_scripts]\nfonttools = fontTools.__main__:main\n')
  write(python + 'Scripts/fonttools.exe', 'generated absolute interpreter launcher')
  write(python + 'Lib/site-packages/fonttools-1.0.dist-info/direct_url.json', '{"url":"file:///C:/build/science/wheel.whl"}')
  write('resources/app/node_modules/.modules.yaml', 'storeDir: C:/build/science/store\n')
  write('resources/app/assets/__pycache__/script.pyc', 'C:/build/science/script.py')
  const result = sanitizeScienceRelease(root)
  expect(result.relativeConsoleCommands).toBe(1)
  expect(result.removedGeneratedFiles).toBe(3)
  expect(existsSync(join(root, python, 'Scripts/fonttools.exe'))).toBe(false)
  expect(readFileSync(join(root, python, 'Scripts/fonttools.cmd'), 'utf8')).toContain('"%~dp0..\\python.exe" -I -B')
  expect(auditScienceRelease(root, ['C:/build/science']).findings).toEqual([])
})

it('detects binary UTF-16 paths, escaped paths and credential bytes without returning their values', () => {
  const { root, write } = fixture()
  const syntheticKey = 'sk-' + '0'.repeat(32)
  write('resources/app/data.bin', Buffer.from('C:\\build\\science\\script.py', 'utf16le'))
  write('resources/app/data.json', JSON.stringify({ path: 'C:\\build\\science\\script.py', key: syntheticKey }))
  write('resources/app/.env', 'MODEL_KEY=' + syntheticKey)
  const result = auditScienceRelease(root, ['C:/build/science'])
  expect(result.findings).toEqual(expect.arrayContaining([
    { path: 'resources/app/data.bin', kind: 'local-path' },
    { path: 'resources/app/data.json', kind: 'local-path' },
    { path: 'resources/app/data.json', kind: 'credential' },
    { path: 'resources/app/.env', kind: 'private-file' },
  ]))
  expect(JSON.stringify(result)).not.toContain(syntheticKey)
  expect(JSON.stringify(result)).not.toContain('C:/build/science')
})

it('refuses cleanup outside a marked Science application', () => {
  const { root, write } = fixture()
  write('resources/app/package.json', '{}')
  expect(() => sanitizeScienceRelease(root)).toThrow('expected a prepared Science application')
  expect(() => auditScienceRelease(root, ['C:/build/science'])).toThrow('expected a prepared Science application')
})
